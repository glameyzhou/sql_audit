CREATE TABLE t_permission (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code        VARCHAR(32)   NOT NULL,
  name        VARCHAR(64)   NOT NULL,
  description VARCHAR(255),
  customized  BOOLEAN       NOT NULL DEFAULT FALSE,
  created_at  TIMESTAMP(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (code)
);

COMMENT ON TABLE t_permission IS '权限点目录 唯一写入方：sqlaudit-server';
COMMENT ON COLUMN t_permission.customized IS '界面是否已配置过：false=代码兜底默认角色，true=按 t_role_permission';

CREATE TABLE t_role_permission (
  permission_id BIGINT      NOT NULL,
  role_id       BIGINT      NOT NULL,
  granted_by    BIGINT,
  created_at    TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (permission_id, role_id)
);

COMMENT ON TABLE t_role_permission IS '角色-权限点关联 唯一写入方：sqlaudit-server';

CREATE INDEX idx_role_permission_role ON t_role_permission (role_id);
